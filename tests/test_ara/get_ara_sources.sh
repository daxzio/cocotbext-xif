#!/usr/bin/env bash
# Generate ara_sources.mak from Bender (run from tests/test_ara with ARA_HW set or passed).
# Usage: ARA_HW=/path/to/ara/hardware ./get_ara_sources.sh
#   or   ./get_ara_sources.sh /path/to/ara/hardware
set -e
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ARA_HW="${1:-${ARA_HW:-$SCRIPT_DIR/../rtl/ara/hardware}}"
ARA_HW="$(cd "$ARA_HW" && pwd)"
OUT="${2:-$SCRIPT_DIR/ara_sources.mak}"

BENDER_CMD=(
    ./bender script verilator
    -t rtl -t cv64a6_imafdcv_sv39
    -t tech_cells_generic_include_tc_sram -t tech_cells_generic_include_tc_clk
    -t exclude_first_pass_decoder -t ara_test -t cva6_test -t verilator
    --define NR_LANES=2 --define VLEN=128
    --define ARIANE_ACCELERATOR_PORT=1 --define COMMON_CELLS_ASSERTS_OFF
)

cd "$ARA_HW"
if ! [[ -x ./bender ]]; then
    echo "get_ara_sources.sh: bender not found or not executable in $ARA_HW" >&2
    exit 1
fi

# Collect all lines; normalize paths to $(ARA_HW)/...
declare -a defines=()
declare -a incdirs=()
declare -a sources=()
# Use a fixed placeholder so we can replace with $(ARA_HW) in the mak file
PLACEHOLDER="__ARA_HW__"

while IFS= read -r line; do
    if [[ "$line" == +define+* ]]; then
        def="${line#+define+}"
        defines+=("$def")
    elif [[ "$line" == +incdir+* ]]; then
        path="${line#+incdir+}"
        # Normalize: replace any prefix up to ara/hardware with placeholder
        if [[ "$path" == *"/ara/hardware"* ]]; then
            path="${path#*ara/hardware}"
            path="${path#/}"
            [[ -n "$path" ]] && path="$PLACEHOLDER/$path"
        fi
        [[ -n "$path" ]] && incdirs+=("$path")
    elif [[ "$line" == /*.sv ]]; then
        path="$line"
        if [[ "$path" == *"/ara/hardware"* ]]; then
            path="${path#*ara/hardware}"
            path="${path#/}"
            [[ -n "$path" ]] && path="$PLACEHOLDER/$path"
        fi
        [[ -n "$path" ]] && sources+=("$path")
    fi
done < <("${BENDER_CMD[@]}" 2>/dev/null)

# Deduplicate (keep order)
declare -A seen
defines_uniq=(); for d in "${defines[@]}"; do [[ -z "${seen[$d]}" ]] && { seen[$d]=1; defines_uniq+=("$d"); }; done
seen=(); incdirs_uniq=(); for i in "${incdirs[@]}"; do [[ -z "${seen[$i]}" ]] && { seen[$i]=1; incdirs_uniq+=("$i"); }; done
seen=(); sources_uniq=(); for s in "${sources[@]}"; do [[ -z "${seen[$s]}" ]] && { seen[$s]=1; sources_uniq+=("$s"); }; done

# Minimal mode: exclude hpdcache, ara_system/soc/testharness; CVA6 keep only include + serdiv.sv (Ara simd_div needs it)
if [[ "${3:-}" == "minimal" ]]; then
  sources_min=()
  for s in "${sources_uniq[@]}"; do
    if [[ "$s" == *"hpdcache"* ]]; then
      : # skip
    elif [[ "$s" == *"ara_system.sv"* ]] || [[ "$s" == *"ara_soc.sv"* ]] || \
       [[ "$s" == *"ara_testharness.sv"* ]] || [[ "$s" == *"accel_dispatcher_ideal.sv"* ]] || \
       [[ "$s" == *"ara_tb"* ]]; then
      : # skip
    elif [[ "$s" == *"deps/cva6/core/"* ]]; then
      [[ "$s" == *"deps/cva6/core/include"* ]] && sources_min+=("$s")
      [[ "$s" == *"deps/cva6/core/serdiv.sv"* ]] && sources_min+=("$s")
    else
      sources_min+=("$s")
    fi
  done
  sources_uniq=("${sources_min[@]}")
  OUT="${OUT%.mak}_minimal.mak"
  echo "Minimal list: ${#sources_uniq[@]} sources (excluded hpdcache, ara_system/soc/tb, cva6 core except include+serdiv)"
fi

# Write mak file; paths use $(ARA_HW) so Makefile must set ARA_HW before including.
{
    echo "# Auto-generated by get_ara_sources.sh - do not edit"
    echo "ARA_EXT_SOURCES += \\"
    n=${#sources_uniq[@]}
    for idx in "${!sources_uniq[@]}"; do
        s="${sources_uniq[$idx]//$PLACEHOLDER/\$(ARA_HW)}"
        (( idx + 1 < n )) && echo "	$s \\" || echo "	$s"
    done
    echo ""
    echo "ARA_VERILOG_INCLUDE_DIRS += \\"
    n=${#incdirs_uniq[@]}
    for idx in "${!incdirs_uniq[@]}"; do
        i="${incdirs_uniq[$idx]//$PLACEHOLDER/\$(ARA_HW)}"
        (( idx + 1 < n )) && echo "	$i \\" || echo "	$i"
    done
    echo ""
    echo "ARA_DEFINES += \\"
    n=${#defines_uniq[@]}
    for idx in "${!defines_uniq[@]}"; do
        d="${defines_uniq[$idx]}"
        (( idx + 1 < n )) && echo "	$d \\" || echo "	$d"
    done
} > "$OUT"
echo "Wrote $OUT (${#sources_uniq[@]} sources, ${#incdirs_uniq[@]} incdirs, ${#defines_uniq[@]} defines)"